def generate() -> set[str]:
    try:
        import pymorphy3
    except ImportError:
        sys.exit(
            "Установите pymorphy3: pip install pymorphy3\n"
            "Это build-time зависимость; runtime её не требует."
        )

    morph = pymorphy3.MorphAnalyzer()
    out: set[str] = set()

    # Уникальность — убираем дубликаты (несколько доменов
    # могут иметь одно слово).
    base = list(dict.fromkeys(BASE_WORDS))
    print(f"Base words: {len(base)}")

    for word in base:
        parses = morph.parse(word)
        if not parses:
            continue
        # Первая parsing = наиболее вероятная лексема.
        # Берём все словоформы из её парадигмы.
        for lexeme_entry in parses[0].lexeme:
            form = lexeme_entry.word
            if not form:
                continue
            # Оставляем в lowercase (для fuzzy lookup case-insensitive).
            # Минимум 2 символа — односимвольные «я», «с» — бесполезный
            # noise для fuzzy matching.
            if len(form) >= 2:
                out.add(form)

    # Добавляем специфичные термины и брэнды, которых в pymorphy3
    # нет (английские), но нужны для распознавания.
    extras = {
        "ооо", "оао", "ао", "зао", "пао", "нко", "ип", "ано",
        "инн", "кпп", "огрн", "огрнип", "оквэд", "окпо", "окато",
        "ндс", "рф", "кв", "руб", "коп", "грн", "usd", "eur", "rub",
        "scania", "volvo", "renault", "daf", "iveco", "mercedes", "man",
        "tensar", "riax", "triax", "triax160",
        "bekom", "gexaform", "camaz", "maz", "gaz",
    }
    out |= extras

    print(f"Generated forms: {len(out)}")
    return out


def main() -> int:
    forms = generate()
    out_path = _REPO_ROOT / "resources" / "ru_lexicon.txt"
    # Сортированный — стабильный diff при пере-генерации.
    out_path.write_text(
        "\n".join(sorted(forms)) + "\n", encoding="utf-8",
    )
    print(f"Wrote {len(forms)} words to {out_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
