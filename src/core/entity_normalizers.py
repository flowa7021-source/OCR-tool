"""Entity normalizers для OCR-вывода: даты / телефоны / адреса.

OCR выдаёт значения в разных форматах даже на одной странице:

    «29.08.2022 г.»      → «29.08.2022»
    «29.08.22»           → «29.08.2022»  (2-digit year → 4-digit)
    «29/08/2022»         → «29.08.2022»
    «29 августа 2022»    → «29.08.2022»  (month name → number)

    «+7(812)441-30-24»   → «+7 (812) 441-30-24»
    «8(812)441 30 24»    → «+7 (812) 441-30-24»
    «тел.:(812) 4413024» → «+7 (812) 441-30-24»

    «125212,г.Москва,ул.Адмирала Макарова,д.6,стр.13»
      → «125212, г. Москва, ул. Адмирала Макарова, д. 6, стр. 13»

Эти normalizers применяются в TextPostprocessor ПЕРЕД парсером,
т.е. парсер всегда видит canonical-формы и не нужно дублировать
логику в extractors. Итог: Excel-вывод byte-stable между
прогонами одного документа на разных сканах/DPI.
"""

from __future__ import annotations

import re

# ---------------------------------------------------------------
# ДАТЫ
# ---------------------------------------------------------------

_MONTHS_RU = {
    "январ": "01", "феврал": "02", "март": "03", "апрел": "04",
    "ма": "05",
    "июн": "06", "июл": "07", "август": "08", "сентябр": "09",
    "октябр": "10", "ноябр": "11", "декабр": "12",
}


def _month_ru_to_num(name: str) -> str | None:
    low = name.lower().strip()
    for stem, num in _MONTHS_RU.items():
        if low.startswith(stem):
            return num
    return None


_DATE_DDMMYYYY_RE = re.compile(
    r"\b(\d{1,2})[./\-](\d{1,2})[./\-](\d{2,4})\b",
)

# «29 августа 2022», «29 августа 2022 года», «29 августа 2022 г.»
# Суффикс «г.» capturing: `(?:\s*г\.)?` — без `\b` в конце, чтобы
# regex-engine гарантированно съел точку после «г». С `\b` (зачем-то
# требует word-char→non-word граничного перехода) backtracking
# оставляет dangling «.» в output'е.
_DATE_WORDY_RE = re.compile(
    r"\b(\d{1,2})\s+"
    r"(январ|феврал|март|апрел|ма|июн|июл|август|"
    r"сентябр|октябр|ноябр|декабр)\w*\s+"
    r"(\d{4})(?:\s*года|\s*г\.)?",
    re.IGNORECASE,
)


def normalize_dates(text: str) -> str:
    """Приводит все даты к формату DD.MM.YYYY.

    Поддерживаем:
      * DD.MM.YYYY, DD/MM/YYYY, DD-MM-YYYY
      * DD.MM.YY → DD.MM.20YY (year 00-69 → 2000-2069; 70-99 → 1970-1999)
      * DD <месяц> YYYY [года]

    Оставляет как есть, если день/месяц > 31/12 (явно не дата,
    может быть частью другого формата).
    """
    def _normalize_ddmmyyyy(m: re.Match[str]) -> str:
        d, mo, y = int(m.group(1)), int(m.group(2)), m.group(3)
        if d < 1 or d > 31 or mo < 1 or mo > 12:
            return m.group(0)
        if len(y) == 2:
            yi = int(y)
            # Простая эвристика для 2-digit year: 00-69 → 2000-2069,
            # 70-99 → 1970-1999. Покрывает реалистичный business-
            # диапазон (ТН из 1999 возможны, но редки).
            y = f"20{y}" if yi <= 69 else f"19{y}"
        return f"{d:02d}.{mo:02d}.{y}"

    def _normalize_wordy(m: re.Match[str]) -> str:
        d = int(m.group(1))
        month_num = _month_ru_to_num(m.group(2))
        if not month_num:
            return m.group(0)
        y = m.group(3)
        if d < 1 or d > 31:
            return m.group(0)
        return f"{d:02d}.{month_num}.{y}"

    text = _DATE_DDMMYYYY_RE.sub(_normalize_ddmmyyyy, text)
    text = _DATE_WORDY_RE.sub(_normalize_wordy, text)
    return text


# ---------------------------------------------------------------
# ТЕЛЕФОНЫ
# ---------------------------------------------------------------

# Собирает любой номер, начинающийся с +7 / 8 / 7, 10-11 цифр
# с возможными разделителями. Игнорирует ИНН (>= 10 цифр подряд)
# через lookbehind по контексту.
_PHONE_RE = re.compile(
    r"(?P<prefix>(?:\+?7|8)[ \-]?)"
    r"\(?(?P<code>\d{3,4})\)?[ \-]?"
    r"(?P<p1>\d{2,3})[ \-]?"
    r"(?P<p2>\d{2})[ \-]?"
    r"(?P<p3>\d{2})(?!\d)",
)


def normalize_phones(text: str) -> str:
    """Приводит телефонные номера к canonical ``+7 (XXX) XXX-XX-XX``.

    Не трогает номера, которые не прошли нашу простую валидацию
    (длина / формат). Это ловит «+7(812)4413024», «8 812 441 30 24»,
    «8-812-441-30-24» и приводит к одному виду.
    """
    def _normalize(m: re.Match[str]) -> str:
        code = m.group("code")
        # Склеиваем все цифры p1+p2+p3 и перераспределяем
        rest = f"{m.group('p1')}{m.group('p2')}{m.group('p3')}"
        if len(rest) != 7:
            return m.group(0)  # нестандартная длина — не трогаем
        return f"+7 ({code}) {rest[:3]}-{rest[3:5]}-{rest[5:]}"

    return _PHONE_RE.sub(_normalize, text)


# ---------------------------------------------------------------
# АДРЕСА
# ---------------------------------------------------------------

# OCR часто слепляет элементы адреса без пробелов:
#   «125212,г.Москва,ул.Адмирала»  → «125212, г. Москва, ул. Адмирала»
# Канонический формат: запятая + пробел между элементами,
# префиксы (г. / ул. / д. / к. / стр. / лит. / оф. / пом.) всегда
# с пробелом после точки.
_ADDR_ELEMENT_PREFIXES = (
    "г", "пос", "р-н", "обл", "край",  # территориальные
    "ул", "пр", "пер", "пл", "наб", "ш", "пр-т", "пр-кт",  # линейные
    "д", "дом", "стр", "корп", "к", "лит", "литера",  # строения
    "оф", "офис", "пом", "помещение", "кв", "комн",  # помещения
    "мкр", "этаж",
)

_ADDR_PREFIX_NO_SPACE = re.compile(
    # «г.Москва» → «г. Москва». Включаем только префиксы, у
    # которых обычно ставится точка (не «мкр»).
    r"\b(" + "|".join(
        re.escape(p) for p in _ADDR_ELEMENT_PREFIXES
    ) + r")\.(?=[А-ЯA-Z0-9])",
    re.IGNORECASE,
)

_ADDR_COMMA_NO_SPACE = re.compile(r",(?=[А-ЯA-Zа-яa-z0-9])")


def normalize_addresses(text: str) -> str:
    """Нормализует адреса: пробелы после запятых и адресных
    префиксов (г., ул., д., стр., оф., пом., кв., мкр).

    Применяется ко всему тексту — но работает только на
    токенах, где прямо встретились characteristic адресные
    маркеры. Не портит прозу.
    """
    text = _ADDR_PREFIX_NO_SPACE.sub(r"\1. ", text)
    text = _ADDR_COMMA_NO_SPACE.sub(", ", text)
    return text


# ---------------------------------------------------------------
# Единая точка входа
# ---------------------------------------------------------------


def normalize_all(text: str) -> str:
    """Применяет все entity normalizers последовательно.

    Порядок: phones (регекс цифр/разделителей) → dates (цифры в
    dd.mm.yyyy formatting) → addresses (пробелы вокруг
    префиксов). Последовательность важна: если сначала запустить
    addresses, «г.Москва,125212» → «г. Москва, 125212», и тогда
    phone-matcher не залезет в «125212» (индекс не-phone).
    """
    if not text:
        return text
    text = normalize_phones(text)
    text = normalize_dates(text)
    text = normalize_addresses(text)
    return text
