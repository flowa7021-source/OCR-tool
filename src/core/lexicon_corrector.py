def _build_variant_lookup() -> dict[str, str]:
    """Inversed lookup: lowercased mangled token → canonical."""
    out: dict[str, str] = {}
    for canonical, variants in LEXICON.items():
        for v in variants:
            key = v.lower()
            # Не переопределяем — первый встретившийся canonical
            # выигрывает (детерминированный порядок). Дубликат
            # одного варианта в нескольких canonical'ах — ошибка
            # словаря; логируем, но не падаем.
            if key in out and out[key] != canonical:
                logger.warning(
                    "lexicon_corrector: вариант %r маппит на оба %r и %r; "
                    "оставляем первый.",
                    v, out[key], canonical,
                )
                continue
            out[key] = canonical
    return out


_LOOKUP = _build_variant_lookup()

# Регекс «слово целиком» — Юникод-aware. \w в Python re по
# умолчанию покрывает кириллицу/латиницу/цифры/_ при unicode-flag
# (включён по умолчанию в Python 3).
_TOKEN_RE = re.compile(r"\b[\w\-]+\b", re.UNICODE)


def _preserve_case(original: str, replacement: str) -> str:
    """Натянуть casing оригинального токена на replacement.

    * Полностью UPPER (≥ 2 chars)        → replacement.upper()
    * Полностью lower                    → replacement.lower()
    * Capitalised (first char upper)     → Title-case
    * Mixed-case / single-char           → replacement как есть

    Это важно: «ГРУЗООТПРАВИТЕЛЬ» (заголовок caps) → caps;
    «грузоотправитель» внутри прозы («лицо грузоотправителя») →
    остаётся lowercase, не Капитализируется насильно.
    """
    if not original:
        return replacement
    if len(original) > 1 and original.isupper():
        return replacement.upper()
    if original.islower():
        return replacement.lower()
    if original[0].isupper():
        return replacement[0].upper() + replacement[1:].lower()
    return replacement


def correct(text: str) -> str:
    """Применяет lexicon-коррекцию ко всему тексту.

    Заменяет mangled-варианты на canonical-формы. Идемпотентно
    (вторая итерация ничего не меняет — canonical → canonical).
    Не выбрасывает исключений; при пустом / None входе возвращает
    его как есть.

    Применяется в :class:`TextPostprocessor` после
    ``autocorrect_russian``: к этому моменту autocorrect уже
    починил мелкие опечатки, lexicon-corrector закрывает
    специфические для ТН/УПД termы.
    """
    if not text or not _LOOKUP:
        return text or ""

    def _replace(m: re.Match[str]) -> str:
        token = m.group(0)
        canonical = _LOOKUP.get(token.lower())
        if canonical is None:
            return token
        return _preserve_case(token, canonical)

    return _TOKEN_RE.sub(_replace, text)


def lexicon_size() -> tuple[int, int]:
    """Returns (num_canonical_words, num_total_variants).

    Используется в health-check / stats — пользователь может
    видеть, насколько богат lexicon.
    """
    canonical_count = len(LEXICON)
    variant_count = sum(len(v) for v in LEXICON.values())
    return canonical_count, variant_count
