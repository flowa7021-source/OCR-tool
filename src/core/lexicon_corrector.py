"""Лексиконно-словарная коррекция OCR-вывода для ТН/УПД.

После Tesseract'а текст ВСЕГДА содержит mangled-варианты одних и
тех же критичных терминов: «Грузаатправитель» вместо
«Грузоотправитель», «Гручополучатель» вместо «Грузополучателя»,
«идентийнииривать» вместо «идентифицировать». OCR-ошибки на
конкретных словах **повторяются** между документами одного
сканера — потому что движок LSTM срабатывает одинаково на
одинаковых рендерах глифов.

Этот модуль — **детерминистичный пост-OCR корректор**: словарь
``CANONICAL → [variants…]`` собран из реальных OCR-выводов на
inputs/TN_k_UPD_*.pdf (декабрь 2026). Применяется в
``TextPostprocessor`` после ``autocorrect_russian`` и
``fix_cyrillic_latin_confusion`` — заменяет mangled-токены на
canonical-форму до того, как парсер ищет section headers.

## Вклад в pipeline

Без коррекции на UPD_36 после OCR:

    «1. Грузаатправитель ja Заказчик услуг по организации»
                ↑↑↑↑↑↑↑↑↑↑↑↑↑↑↑
                парсер не матчит как section header

С коррекцией:

    «1. Грузоотправитель ja Заказчик услуг по организации»
                ↑↑↑↑↑↑↑↑↑↑↑↑↑↑↑↑
                _BARE / _NUMBERED регексы парсера матчат → секция найдена

## Как добавлять новые варианты

1. Открой OCR-вывод проблемного документа (run_golden.py с
   --verbose покажет, какие поля не нашлись).
2. Найди mangled-форму критичного слова в OCR-тексте.
3. Добавь её в список вариантов соответствующей canonical-формы
   ниже. Mangled-форма должна быть НЕОДНОЗНАЧНОЙ — т.е. её НЕ
   может встретиться в правильном русском тексте как самостоятельное
   слово (иначе риск over-correction).
4. Локально прогони ``python scripts/run_golden.py --verbose`` —
   accuracy должна вырасти или остаться той же.

## Тонкости

* **Case preservation.** Если оригинальный mangled-токен был
  ЗАГЛАВНЫЙ (например, в section header «ГРУЗООТПРАВИТЕЛЬ»), то
  и canonical вернётся ЗАГЛАВНЫМ. Это важно для парсера: он
  отличает заголовок от обычного упоминания.

* **Word boundary.** Регекс ``\\b\\w+\\b`` гарантирует, что замена
  происходит только на полных токенах, не подстроках. «Грузо»
  внутри «Грузоподъёмность» НЕ заменится.

* **Single pass.** Все варианты собраны в один lookup-dict,
  одно прохождение по тексту. На 30 KB OCR-выходе ~1 мс.

* **Неоднозначные mangled-варианты НЕ добавляем.** Например,
  «груз» может быть и canonical «груз», и mangled «гр[у]з[а]».
  Такое не корректируем — рискуем сломать legitimate использование.
"""

